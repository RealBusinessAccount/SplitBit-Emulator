; The 16-bit segmented sieve rewritten for SplitBit's four-Data-Pointer ISA.
;
; This deliberately implements the same algorithm and emits the same text as
; 16bitSegmentedSieve.asm, making the two versions useful as a direct comparison.
; DP0 walks PrimeStates, DP1 holds Page, DP2 walks Segment, and volatile DP3
; marks multiples.  CALL preserves the first three pointers automatically.

#Include services.asm

#Program

    #Base 0x2000

start:
  RSTA
  SETD.1 Page
  STA.1

nextPage:
  SETD.2 Segment
  RSTA
  RSTB
clearSegment:
  STB.2
  INCD.2
  INCA
  BRA segmentCleared
  BRI clearSegment

segmentCleared:
  ; Zero and one are not prime.
  LDA.1
  BRA excludeZeroAndOne
  BRI markSegment
excludeZeroAndOne:
  SETD.2 Segment
  INIA 0x01
  STA.2
  INCD.2
  STA.2

markSegment:
  SETD.0 PrimeStates
  INIA 0d54
primeLoop:
  CALL processPrime
  DPUP.0 0d03
  DECA
  BRA scanSegment
  BRI primeLoop

scanSegment:
  SETD.2 Segment
  RSTA
scanLoop:
  LDB.2
  BRB emitPrime
scanNext:
  INCD.2
  INCA
  BRA advancePage
  BRI scanLoop

emitPrime:
  CALL printCandidateHex
  BRI scanNext

advancePage:
  LDA.1
  INCA
  STA.1
  BRA finished
  BRI nextPage

finished:
  CALL lineFeed
  SWI osExit  ; Return to CosmOS.

; DP0 points at a PrimeStates entry. CALL restores it on return.
processPrime:
  INCD.0
  LDA.0
  LDB.1
  XOR
  BRQ primeIsActive
  RET

primeIsActive:
  ; B is the prime and A its current offset.
  DECD.0
  LDB.0
  DPUP.0 0d02
  LDA.0

  ; DP3 = Segment + offset. Only this one initial pointer copy needs the Stack.
  SETD.3 Segment
  PSHB
  PSHD.3
  POPB
  CCF
  ADD
  PSHQ
  POPD.3
  POPB

markPrimeLoop:
  INIA 0x01
  STA.3

  ; Add the prime to DP3's low byte. A carry crosses into the next window.
  PSHD.3
  POPA
  CCF
  ADD
  PSHQ
  POPD.3
  BRC primeFinished
  BRI markPrimeLoop

primeFinished:
  ; DP0 is on the offset byte; advance the saved high byte and save Q as
  ; the wrapped offset for the following page.
  DECD.0
  LDA.0
  INCA
  STA.0
  INCD.0
  STQ.0
  RET

printCandidateHex:
  PSHA
  LDA.1
  CALL printByteHex
  POPA
  CALL printByteHex
  CALL blankSpace
  RET

